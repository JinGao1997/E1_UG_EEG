def get_first_existing_col(df: pd.DataFrame, candidates: list[str]) -> str | None:
    for c in candidates:
        if c in df.columns:
            return c
    return None


def normalize_emotion(x):
    if pd.isna(x):
        return x
    return str(x).strip().lower()


