def detect_project_root(start: Path) -> Path | None:
    """Climb up directories to find the project root containing 'results'."""
    for parent in [start.parent] + list(start.parents)[:6]:
        if (parent / "results").exists():
            return parent
    return None


def choose_output_root(project_root: Path, prefer_debug: bool = False) -> Path:
    """
    Choose between Pub_Output_Final and Debug_Output_Final.
    """
    pub_root = project_root / "results" / "Behavioral" / "Pub_Output_Final"
    dbg_root = project_root / "results" / "Behavioral" / "Debug_Output_Final"

    if prefer_debug and dbg_root.exists():
        return dbg_root
    if pub_root.exists():
        return pub_root
    if dbg_root.exists():
        return dbg_root

    raise FileNotFoundError(
        "No output root found. Expected either:\n"
        f"  {pub_root}\n"
        f"  {dbg_root}"
    )


def find_trials_csv(project_root: Path) -> Path | None:
    """
    Locate trials.csv using the path defined in Sta_Behaviour.Rmd, then fallback.
    """
    target = project_root / "data" / "02_Pipeline_Output" / "Method_Regression" / "Stimulus_Locked" / "trials.csv"
    if target.exists():
        return target

    candidates = list(project_root.rglob("trials.csv"))
    if not candidates:
        return None
    preferred = [c for c in candidates if "Method_Regression" in str(c)]
    return preferred[0] if preferred else candidates[0]


